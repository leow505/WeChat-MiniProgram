const DICTS = { zh, en }

function detect() {
  const stored = wx.getStorageSync(STORAGE_KEY)
  if (stored && DICTS[stored]) return stored

  let lang = ''
  try {
    lang = (wx.getAppBaseInfo ? wx.getAppBaseInfo() : wx.getSystemInfoSync()).language || ''
  } catch (e) {
    lang = ''
  }
  return String(lang).toLowerCase().indexOf('zh') === 0 ? 'zh' : 'en'
}

let locale = 'zh'

function init() {
  locale = detect()
  return locale
}

function get() {
  return locale
}

function set(next) {
  if (!DICTS[next]) return locale
  locale = next
  wx.setStorageSync(STORAGE_KEY, next)
  return locale
}

function interpolate(str, params) {
  if (!params) return str
  return String(str).replace(/\{(\w+)\}/g, (m, k) => (params[k] == null ? m : params[k]))
}

function t(key, params) {
  const dict = DICTS[locale] || zh
  const raw = dict[key] != null ? dict[key] : zh[key] != null ? zh[key] : key
  return interpolate(raw, params)
}

/** Whole dictionary for `{{t.key}}` in WXML. */
function pack() {
  return DICTS[locale] || zh
}

/** Localize a server error, falling back to a generic string. */
function errText(err) {
  const table = ERR[locale] || ERR.zh
  if (err && err.code && table[err.code]) return table[err.code]
  return table.DEFAULT
}

module.exports = {
  init,
  get,
  set,
  t,
  pack,
  errText,
  locales: Object.keys(DICTS),
}
